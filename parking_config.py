def is_valid_pair(theta, floor, min_park_vol=MIN_PARK_VOL):
    """Правило валидности: theta - floor > min_park_vol.

    Сравнение с допуском VALIDITY_EPS: без него пара ровно на границе
    (0.05/0.04, разность 0.01) проходит из-за ошибки float
    (0.010000000000000002 > 0.01) и число конфигураций становится 7 вместо 6.
    """
    return (theta - floor) > (min_park_vol + VALIDITY_EPS)


def valid_configs(theta_grid=THETA_GRID, floor_grid=FLOOR_GRID):
    """Список валидных пар (theta, floor) по правилу валидности."""
    return [(t, f) for t in theta_grid for f in floor_grid
            if is_valid_pair(t, f)]


def cell_count(n_configs, n_scenarios=None, n_seeds=None, n_folds=None):
    """Число ячеек сетки: конфигурации x сценарии x сиды x фолды."""
    n_scenarios = len(COMMISSION_SCENARIOS) if n_scenarios is None else n_scenarios
    n_seeds = len(SEEDS) if n_seeds is None else n_seeds
    n_folds = len(EVAL_FOLDS) if n_folds is None else n_folds
    return n_configs * n_scenarios * n_seeds * n_folds


